"""Pre-recruiting sizing check for decision 6 (audit 8, B1).

Estimates, by simulation, the probability that each gate passes under the fixed scenarios of
decision 6, section 9, for designs in the search space. It is a feasibility check run before
recruiting, not the frozen simulation that the analyst writes later.

Model (all parameters below are the conservative defaults that decision 6 names):
- Every tempting task targets the set its test uses (the binding targeting rule).
- Violations: a task has a heterogeneity factor g ~ Gamma(mean 1, CV), shared by the arms of
  that task. A run of an arm has Poisson(rate * g) violations.
- Success: a task has base success p ~ Beta(mean 0.7, sd 0.15), shared; a run succeeds with
  probability p, minus the scenario's cost for arm V.
- Working time: a task has a log-median mu ~ N(0, 0.5), shared; a run's log time is mu plus
  N(0, SIGMA_RUN), plus log(1 + time cost) for arm V. A failed run counts as the budget,
  3 times the task's median.
- Escaped defects: Poisson(0.1) per run in every arm. Vulcan false positives: 2% of runs.
- Tests: exact sign-flip over informative tasks (Monte Carlo with FLIPS sign patterns), at
  alpha 0.05, with the half-rate condition, at least 5 informative tasks and 10 events. Bounds
  N0 to N3 use a one-sided 95% t-bound over tasks (an approximation of the inverted test).

Usage: python -I sizing.py   (writes results.md next to this file)
"""
import os
import numpy as np

RNG = np.random.default_rng(20261021)
CV = 1.0
SIGMA_RUN = 0.5
FLIPS = 2000
SIMS = 400


def gamma_factor(n):
    k = 1.0 / CV ** 2
    return RNG.gamma(k, 1.0 / k, size=n)


def signflip_p(d):
    d = d[d != 0]
    n = len(d)
    if n < 5:
        return None
    obs = d.sum()
    signs = RNG.choice([-1.0, 1.0], size=(FLIPS, n))
    return float(((signs * np.abs(d)).sum(axis=1) >= obs - 1e-12).mean())


def p1_pass(better, worse):
    """better, worse: arrays (tasks, runs) of violation counts."""
    if better.sum() + worse.sum() < 10:
        return False
    rb, rw = better.mean(axis=1), worse.mean(axis=1)
    p = signflip_p(rw - rb)
    if p is None or p >= 0.05:
        return False
    return rb.mean() <= 0.5 * rw.mean()


def tbound(x):
    from scipy.stats import t
    n = len(x)
    sd = x.std(ddof=1) if n > 1 else 0.0
    return x.mean() + t.ppf(0.95, n - 1) * sd / np.sqrt(n)


def violations(rate, g, runs):
    return RNG.poisson(np.outer(rate * g, np.ones(runs)))


def milestone4(tasks, runs, tempting, rate_r, rate_v, cost_s, cost_t, margin_s, margin_t):
    # Q2 on U*: every tempting task targets U*.
    g = gamma_factor(tempting)
    q2 = p1_pass(violations(rate_v, g, runs), violations(rate_r, g, runs))
    if not q2:
        return False
    # N0, N1 over all tasks.
    a, b = 0.7 * 7.0, 0.3 * 7.0           # Beta with mean 0.7, sd about 0.15
    p = RNG.beta(a, b, size=tasks)
    sr = RNG.random((tasks, runs)) < p[:, None]
    sv = RNG.random((tasks, runs)) < np.clip(p - cost_s, 0, 1)[:, None]
    if tbound(sr.mean(axis=1) - sv.mean(axis=1)) > margin_s:
        return False
    mu = RNG.normal(0, 0.5, size=tasks)[:, None]
    tr = np.exp(mu + RNG.normal(0, SIGMA_RUN, (tasks, runs)))
    tv = np.exp(mu + RNG.normal(0, SIGMA_RUN, (tasks, runs)) + np.log(1 + cost_t))
    budget = np.exp(mu + np.log(3.0))
    tr = np.where(sr, tr, budget)
    tv = np.where(sv, tv, budget)
    if tbound(np.log(tv.mean(axis=1) / tr.mean(axis=1))) > np.log(margin_t):
        return False
    # N2, N3.
    dv = RNG.poisson(0.1, (tasks, runs)).mean(axis=1)
    dr = RNG.poisson(0.1, (tasks, runs)).mean(axis=1)
    if tbound(dv - dr) > 0.1:
        return False
    fp = (RNG.random((tasks, runs)) < 0.02).mean(axis=1)
    if tbound(fp) > 0.1:
        return False
    return True


def m4_power(tasks, runs, tempting, scenario, margin_s=0.10, margin_t=1.10):
    rate_r, rate_v, cs, ct = scenario
    return np.mean([milestone4(tasks, runs, tempting, rate_r, rate_v, cs, ct, margin_s, margin_t)
                    for _ in range(SIMS)])


def m05_power(targeted, runs):
    # Q1 under L: P at 0.4, R at 0.05, every tempting task targets S.
    ok = 0
    for _ in range(SIMS):
        g = gamma_factor(targeted)
        ok += p1_pass(violations(0.05, g, runs), violations(0.4, g, runs))
    return ok / SIMS


SCEN = {"Z": (0.4, 0.4, 0.0, 0.0), "L": (0.4, 0.05, 0.0, 0.0), "L+cost": (0.4, 0.05, 0.15, 0.20)}


def main():
    globals()['SIMS'] = 400
    out = ["# Pre-recruiting sizing check", "",
           "Generated by `sizing.py` (seed 20261021, %d simulations per cell, %d sign patterns per "
           "test). CV %.1f, run time spread %.1f. Every tempting task targets the tested set." %
           (SIMS, FLIPS, CV, SIGMA_RUN), ""]
    out += ["## Milestone 0.5: P(Q1 passes | L)", "", "| Targeted tasks | 5 runs | 10 runs |",
            "|---|---|---|"]
    for k in (6, 8, 10, 12, 16):
        out.append("| %d | %.2f | %.2f |" % (k, m05_power(k, 5), m05_power(k, 10)))
    out += ["", "## Milestone 4: P(Continue) at the old margins (10 points, 1.10)", "",
            "| Tasks | Tempting | Runs | Z | L | L+cost |", "|---|---|---|---|---|---|"]
    for tasks, tempting in ((14, 8), (24, 18), (32, 24)):
        for runs in (5, 10):
            row = [m4_power(tasks, runs, tempting, SCEN[s], 0.10, 1.10) for s in ("Z", "L", "L+cost")]
            out.append("| %d | %d | %d | %.2f | %.2f | %.2f |" % (tasks, tempting, runs, *row))
    globals()['SIMS'] = 1000
    out += ["", "## Milestone 4: P(Continue) at the adopted margins (12 points, 1.15)", "",
            "Three quarters of the tasks are tempting. R's rate is 0.4 per run, or 0.2 to test a "
            "lower measured baseline; V's rate is one eighth of R's under L.", "",
            "| Tasks | Tempting | Runs | R rate | Z | L | L+cost |", "|---|---|---|---|---|---|---|"]
    for tasks, tempting in ((24, 18), (28, 21), (32, 24)):
        for runs in (8, 10):
            for rr in (0.4, 0.2):
                sc = {"Z": (rr, rr, 0, 0), "L": (rr, rr / 8, 0, 0), "L+cost": (rr, rr / 8, 0.15, 0.20)}
                row = [m4_power(tasks, runs, tempting, sc[s], 0.12, 1.15) for s in ("Z", "L", "L+cost")]
                out.append("| %d | %d | %d | %.1f | %.2f | %.2f | %.2f |" % (tasks, tempting, runs, rr, *row))
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results.md")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
