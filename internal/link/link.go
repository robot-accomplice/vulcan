// Package link generates the container's main package and the leaves' registration files from
// the checked wiring plan (spec §6, Appendix F), and runs the go command.
package link

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/robot-accomplice/vulcan/internal/check"
	"github.com/robot-accomplice/vulcan/internal/decl"
	"github.com/robot-accomplice/vulcan/internal/gen"
	"github.com/robot-accomplice/vulcan/internal/project"
)

var flagTypes = map[string]string{"String": "string", "Int": "int", "Int64": "int64", "Float64": "float64", "Bool": "bool", "Duration": "duration"}

type writer struct {
	p       *project.Project
	aliases map[string]string // import path -> alias
	b       bytes.Buffer
}

func (w *writer) alias(path string) string {
	if a, ok := w.aliases[path]; ok {
		return a
	}
	a := fmt.Sprintf("vulcan_l%d", len(w.aliases))
	w.aliases[path] = a
	return a
}

func (w *writer) qual(self string) types.Qualifier {
	return func(p *types.Package) string {
		if p.Path() == self {
			return ""
		}
		if w.p.ByPath[p.Path()] == nil && !strings.Contains(p.Path(), ".") && !strings.Contains(p.Path(), "/") {
			w.aliases[p.Path()] = p.Path()
			return p.Path()
		}
		return w.alias(p.Path())
	}
}

// expr writes a value from system.vulcan: the constant that the checker computed, so that the
// generated code needs none of system.vulcan's imports.
func (w *writer) expr(v *decl.Value) string {
	if v.Lit != "" {
		return v.Lit
	}
	return "(" + v.Text + ")"
}

// settings writes a settings literal of type t.
func (w *writer) settings(s *decl.Settings, t types.Type, self string, flagVar string, plan *check.Plan) string {
	var parts []string
	if s != nil {
		for _, it := range s.Items {
			switch it.Value.Kind {
			case decl.FlagValue:
				var getter string
				for _, f := range plan.Flags {
					if f.Name == it.Value.Flag.Name {
						getter = f.Getter
					}
				}
				parts = append(parts, fmt.Sprintf("%s: %s.%s(%q)", it.Key, flagVar, getter, it.Value.Flag.Name))
			case decl.ExprValue:
				parts = append(parts, fmt.Sprintf("%s: %s", it.Key, w.expr(it.Value)))
			}
		}
	}
	return fmt.Sprintf("%s{%s}", types.TypeString(t, w.qual(self)), strings.Join(parts, ", "))
}

// Write generates main and the registration files into the build directory.
func Write(p *project.Project, plan *check.Plan) error {
	dir := gen.BuildDir(p)
	funcsByLeaf := map[*project.Package][]check.LeafFunc{}
	for _, f := range plan.Funcs {
		funcsByLeaf[f.Leaf] = append(funcsByLeaf[f.Leaf], f)
	}
	for l, fs := range funcsByLeaf {
		w := &writer{p: p, aliases: map[string]string{}}
		var body bytes.Buffer
		for _, f := range fs {
			fmt.Fprintf(&body, "func Vulcan_%s(ctx context.Context, f *rt.Flags) error {\n", f.Kind)
			if f.SetType != nil {
				fmt.Fprintf(&body, "\treturn %s(ctx, %s)\n}\n\n", f.Kind, w.settings(l.Entry.Settings, f.SetType, l.ImportPath, "f", plan))
			} else {
				fmt.Fprintf(&body, "\t_ = f\n\treturn %s(ctx)\n}\n\n", f.Kind)
			}
		}
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by vulcan. DO NOT EDIT.\n\npackage %s\n\nimport (\n\t\"context\"\n\n\trt %q\n", l.GoName, check.RuntimeRT)
		for _, line := range w.imports(l.ImportPath) {
			fmt.Fprintf(&b, "\t%s\n", line)
		}
		b.WriteString(")\n\n")
		b.Write(body.Bytes())
		if err := os.WriteFile(filepath.Join(dir, filepath.FromSlash(l.Dir), "vulcan_register.go"), formatted(b.Bytes()), 0o644); err != nil {
			return err
		}
	}
	return writeMain(p, plan, dir, funcsByLeaf)
}

func (w *writer) imports(self string) []string {
	var out []string
	var paths []string
	for path := range w.aliases {
		if path != self {
			paths = append(paths, path)
		}
	}
	sort.Strings(paths)
	for _, path := range paths {
		a := w.aliases[path]
		if a == path {
			out = append(out, fmt.Sprintf("%q", path))
		} else {
			out = append(out, fmt.Sprintf("%s %q", a, path))
		}
	}
	return out
}

func writeMain(p *project.Project, plan *check.Plan, dir string, funcs map[*project.Package][]check.LeafFunc) error {
	w := &writer{p: p, aliases: map[string]string{}}
	var body bytes.Buffer
	body.WriteString("func vulcan_construct(f *rt.Flags) error {\n\t_ = f\n")
	byLeaf := map[*project.Package][]*check.Instance{}
	for _, inst := range plan.Instances {
		byLeaf[inst.Leaf] = append(byLeaf[inst.Leaf], inst)
	}
	for _, l := range plan.Order {
		for _, inst := range byLeaf[l] {
			a := w.alias(l.ImportPath)
			v := fmt.Sprintf("vulcan_i%d", inst.ID)
			switch {
			case inst.IsType:
				fmt.Fprintf(&body, "\t%s := new(%s.%s)\n", v, a, inst.Name)
			default:
				args := ""
				if inst.SetType != nil {
					args = w.settings(inst.Settings, inst.SetType, "", "f", plan)
				}
				if inst.ReturnsErr {
					fmt.Fprintf(&body, "\t%s, err := %s.%s(%s)\n\tif err != nil {\n\t\treturn rt.Constructed(%q, err)\n\t}\n", v, a, inst.Name, args, l.Name+"."+inst.Name)
				} else {
					fmt.Fprintf(&body, "\t%s := %s.%s(%s)\n", v, a, inst.Name, args)
				}
			}
			for _, b := range plan.Binds {
				if b.Inst == inst {
					fmt.Fprintf(&body, "\t%s.%s = %s\n", w.alias(b.Need.ImportPath), b.Port, v)
				}
			}
			fmt.Fprintf(&body, "\t_ = %s\n", v)
		}
	}
	body.WriteString("\treturn nil\n}\n\n")
	steps := func(kind string) string {
		var s bytes.Buffer
		fmt.Fprintf(&s, "func(f *rt.Flags) []rt.Step {\n\t\treturn []rt.Step{\n")
		for _, l := range plan.Order {
			for _, fn := range funcs[l] {
				if fn.Kind == kind {
					fmt.Fprintf(&s, "\t\t\t{Leaf: %q, Fn: func(ctx context.Context) error { return %s.Vulcan_%s(ctx, f) }},\n", l.Name, w.alias(l.ImportPath), kind)
				}
			}
		}
		s.WriteString("\t\t}\n\t}")
		return s.String()
	}
	var flags bytes.Buffer
	for _, f := range plan.Flags {
		fmt.Fprintf(&flags, "\t\t\t{Name: %q, Type: %q", f.Name, flagTypes[f.Getter])
		if f.Default != nil {
			fmt.Fprintf(&flags, ", Default: %s(%s), HasDefault: true", f.GoType, w.expr(f.Default))
		}
		flags.WriteString("},\n")
	}
	timeout := "0"
	if v := p.Config("shutdown_timeout"); v != nil && v.Kind == decl.ExprValue {
		timeout = "time.Duration(" + w.expr(v) + ")"
	}
	setups, startups := steps("setup"), steps("startup")
	var b bytes.Buffer
	b.WriteString("// Code generated by vulcan from system.vulcan. DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"context\"\n\t\"os\"\n\t\"time\"\n\n")
	fmt.Fprintf(&b, "\trt %q\n", check.RuntimeRT)
	for _, line := range w.imports("") {
		if line == `"time"` || line == `"context"` || line == `"os"` {
			continue
		}
		fmt.Fprintf(&b, "\t%s\n", line)
	}
	b.WriteString(")\n\nvar _ = time.Second\nvar _ context.Context\n\n")
	fmt.Fprintf(&b, "func main() {\n\tos.Exit(rt.Main(rt.Program{\n\t\tName: %q,\n\t\tShutdownTimeout: %s,\n\t\tFlags: []rt.FlagSpec{\n%s\t\t},\n\t\tConstruct: vulcan_construct,\n\t\tSetups: %s,\n\t\tStartups: %s,\n\t}))\n}\n\n",
		p.System.Name+"/"+p.Container.Name, timeout, flags.String(), setups, startups)
	b.Write(body.Bytes())
	main := filepath.Join(dir, gen.MainDir)
	if err := os.MkdirAll(main, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(main, "main.go"), formatted(b.Bytes()), 0o644)
}

// formatted runs gofmt on generated code, and keeps the input when it does not parse, so that the
// go command reports the error.
func formatted(b []byte) []byte {
	if f, err := format.Source(b); err == nil {
		return f
	}
	return b
}
