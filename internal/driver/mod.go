package driver

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"

	"golang.org/x/mod/modfile"

	"github.com/robot-accomplice/vulcan/internal/check"
	"github.com/robot-accomplice/vulcan/internal/gen"
	"github.com/robot-accomplice/vulcan/internal/project"
)

// ModTidy runs go mod tidy over the Go code that the compiler generates, and writes go.mod and
// go.sum back to the project (spec §6, "Modules"). The project's own replace directives are kept
// as they were; the build directory's replace of the runtime is not written back.
func ModTidy(root string) (string, error) {
	p, err := project.Load(root)
	if err != nil {
		return "", err
	}
	if p.System == nil {
		return "", fmt.Errorf("system.vulcan does not parse; run vulcan check")
	}
	if err := gen.WriteLeaves(p, true, nil); err != nil {
		return "", err
	}
	dir := gen.BuildDir(p)
	// The generated main always imports the runtime, so tidy must keep it.
	rt := []byte("// Code generated by vulcan. DO NOT EDIT.\n\npackage main\n\nimport _ \"" + check.RuntimeRT + "\"\n")
	if err := os.WriteFile(filepath.Join(dir, gen.MainDir, "vulcan_rt.go"), rt, 0o644); err != nil {
		return "", err
	}
	cmd := exec.Command("go", "mod", "tidy")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod")
	if out, err := cmd.CombinedOutput(); err != nil {
		return string(out), fmt.Errorf("go mod tidy failed")
	}
	built, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		return "", err
	}
	nf, err := modfile.Parse("go.mod", built, nil)
	if err != nil {
		return "", err
	}
	of, err := modfile.Parse("go.mod", p.GoMod, nil)
	if err != nil {
		return "", err
	}
	for _, r := range append([]*modfile.Replace{}, nf.Replace...) {
		if err := nf.DropReplace(r.Old.Path, r.Old.Version); err != nil {
			return "", err
		}
	}
	for _, r := range of.Replace {
		if err := nf.AddReplace(r.Old.Path, r.Old.Version, r.New.Path, r.New.Version); err != nil {
			return "", err
		}
	}
	nf.Cleanup()
	out, err := nf.Format()
	if err != nil {
		return "", err
	}
	if err := os.WriteFile(filepath.Join(p.Root, "go.mod"), out, 0o644); err != nil {
		return "", err
	}
	if sum, err := os.ReadFile(filepath.Join(dir, "go.sum")); err == nil {
		if err := os.WriteFile(filepath.Join(p.Root, "go.sum"), sum, 0o644); err != nil {
			return "", err
		}
	}
	return "", nil
}
